/**
 * Turns `data/catalog.json` + `data/yaml/*.yaml` into two generated TypeScript
 * modules. Static modules rather than runtime `fs` reads, so the catalogue
 * survives Next.js tracing and ships cleanly to Vercel.
 *
 *   src/generated/entries.ts — metadata for every dashboard (always loaded)
 *   src/generated/yaml.ts    — id -> YAML (dynamically imported on demand)
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CURATED_ENTRIES } from "../src/curated";
import { catalogSchema, type DashboardEntry } from "../src/schema";

const here = path.dirname(fileURLToPath(import.meta.url));
const DATA_DIR = path.join(here, "..", "data");
const YAML_DIR = path.join(DATA_DIR, "yaml");
const OUT_DIR = path.join(here, "..", "src", "generated");

mkdirSync(OUT_DIR, { recursive: true });

let entries: DashboardEntry[] = [];
if (existsSync(path.join(DATA_DIR, "catalog.json"))) {
  const raw = JSON.parse(readFileSync(path.join(DATA_DIR, "catalog.json"), "utf8"));
  const parsed = catalogSchema.safeParse(raw);
  if (!parsed.success) {
    console.error("catalog.json failed validation:", parsed.error.issues.slice(0, 5));
    process.exit(1);
  }
  entries = parsed.data.entries;
} else {
  console.warn("No catalog.json found — bundling curated entries only.");
}

// Curated entries always win, and are always present.
const byId = new Map<string, DashboardEntry>();
for (const e of entries) byId.set(e.id, e);
for (const e of CURATED_ENTRIES) byId.set(e.id, e);

const yamlMap: Record<string, string> = {};
for (const entry of byId.values()) {
  if (entry.inlineYaml) {
    yamlMap[entry.id] = entry.inlineYaml;
    continue;
  }
  if (!entry.yamlFile) continue;
  const file = path.join(YAML_DIR, entry.yamlFile);
  if (!existsSync(file)) {
    entry.yamlFile = null;
    entry.renderable = false;
    entry.yamlOmittedReason = "YAML file missing from the data directory.";
    continue;
  }
  yamlMap[entry.id] = readFileSync(file, "utf8");
}

// Metadata module carries no YAML; keep entity lists bounded.
const slim = [...byId.values()]
  .map((e) => ({
    ...e,
    inlineYaml: null,
    analysis: { ...e.analysis, entities: e.analysis.entities.slice(0, 150) },
  }))
  .sort((a, b) => {
    if (a.source.kind === "curated" && b.source.kind !== "curated") return -1;
    if (b.source.kind === "curated" && a.source.kind !== "curated") return 1;
    return (b.stars ?? 0) - (a.stars ?? 0);
  });

const header = "// GENERATED by packages/catalog/scripts/bundle.ts — do not edit by hand.\n";

writeFileSync(
  path.join(OUT_DIR, "entries.ts"),
  `${header}import type { DashboardEntry } from "../schema";\n\nexport const ENTRIES: DashboardEntry[] = ${JSON.stringify(slim, null, 1)} as unknown as DashboardEntry[];\n\nexport const GENERATED_AT = ${JSON.stringify(new Date().toISOString())};\n`,
  "utf8",
);

writeFileSync(
  path.join(OUT_DIR, "yaml.ts"),
  `${header}export const DASHBOARD_YAML: Record<string, string> = ${JSON.stringify(yamlMap, null, 0)};\n`,
  "utf8",
);

const yamlCount = Object.keys(yamlMap).length;
const diskYaml = existsSync(YAML_DIR) ? readdirSync(YAML_DIR).length : 0;
console.log(
  `Bundled ${slim.length} entries (${yamlCount} with YAML, ${diskYaml} yaml files on disk).`,
);
